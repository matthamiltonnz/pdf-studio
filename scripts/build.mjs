import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));

async function main() {
  const workerPath = path.join(root, 'node_modules/pdfjs-dist/legacy/build/pdf.worker.min.js');
  const worker = await readFile(workerPath);
  const workerBase64 = worker.toString('base64');
  const generatedDir = path.join(root, 'src/generated');
  await mkdir(generatedDir, { recursive: true });
  await writeFile(
    path.join(generatedDir, 'worker.js'),
    `// Generated by scripts/build.mjs — do not edit.\nexport default ${JSON.stringify(workerBase64)};\n`,
    'utf8',
  );

  const result = await build({
    entryPoints: [path.join(root, 'src/main.js')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['chrome100', 'edge100', 'firefox100', 'safari15'],
    minify: true,
    write: false,
    outfile: path.join(dist, 'pdf-studio.js'),
    legalComments: 'none',
    logLevel: 'warning',
    define: {
      __APP_VERSION__: JSON.stringify(pkg.version || '1.0.0'),
    },
  });

  const jsFile = result.outputFiles.find((file) => file.path.endsWith('.js'));
  if (!jsFile) throw new Error('esbuild did not produce a JavaScript bundle.');
  const js = jsFile.text.replace(/<\/script/gi, '<\\/script');
  const css = await readFile(path.join(root, 'src/styles.css'), 'utf8');
  const template = await readFile(path.join(root, 'src/index.html'), 'utf8');

  if (!template.includes('/*__STYLES__*/') || !template.includes('/*__SCRIPT__*/')) {
    throw new Error('The HTML template is missing its injection markers.');
  }

  const html = template
    .replace('/*__STYLES__*/', () => css)
    .replace('/*__SCRIPT__*/', () => js);

  await mkdir(dist, { recursive: true });
  const outputPath = path.join(dist, 'pdf-studio.html');
  await writeFile(outputPath, html, 'utf8');
  await writeFile(path.join(dist, 'index.html'), html, 'utf8');

  const kb = Math.round(Buffer.byteLength(html) / 1024);
  console.log(`Built ${path.relative(root, outputPath)} (${kb} KB) and dist/index.html`);
  console.log(`PDF.js worker embedded: ${Math.round(worker.length / 1024)} KB`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
